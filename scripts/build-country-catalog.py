#!/usr/bin/env python3
"""Generate TravelLog/Services/CountryCatalogData.swift from the mledoze
countries dataset (https://github.com/mledoze/countries, ODbL).

Emits, per ISO 3166-1 alpha-2 code:
  - approximate total area in km^2 (drives the per-country hex-coverage %)
  - the UN-member set (193; drives the "X of 193 UN countries" stat)
  - the territory -> UN-member fold map (visiting Puerto Rico counts as
    the United States on the UN stat; hand-authored below because the
    dataset carries no sovereign linkage)

Usage:
  curl -sL https://raw.githubusercontent.com/mledoze/countries/master/countries.json -o /tmp/countries.json
  python3 scripts/build-country-catalog.py /tmp/countries.json

The script hard-fails (SystemExit) on any internal inconsistency: UN count
!= 193, a fold key that is itself a UN member, a fold target that is not,
or a non-member code that is neither folded nor deliberately standalone.
"""

import argparse
import json
import os
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "TravelLog" / "Services" / "CountryCatalogData.swift"

# Dependent territories folded into their sovereign UN member for the
# "of 193 UN countries" numerator. Hand-authored; factual administrative
# status as of 2026.
FOLDS = {
    # United States
    "AS": "US", "GU": "US", "MP": "US", "PR": "US", "VI": "US", "UM": "US",
    # United Kingdom (incl. Crown dependencies)
    "AI": "GB", "BM": "GB", "IO": "GB", "VG": "GB", "KY": "GB", "FK": "GB",
    "GI": "GB", "MS": "GB", "PN": "GB", "SH": "GB", "TC": "GB", "GS": "GB",
    "GG": "GB", "JE": "GB", "IM": "GB",
    # Netherlands
    "AW": "NL", "CW": "NL", "SX": "NL", "BQ": "NL",
    # Denmark
    "GL": "DK", "FO": "DK",
    # France
    "BL": "FR", "GF": "FR", "GP": "FR", "MF": "FR", "MQ": "FR", "NC": "FR",
    "PF": "FR", "PM": "FR", "RE": "FR", "TF": "FR", "WF": "FR", "YT": "FR",
    # China (SARs)
    "HK": "CN", "MO": "CN",
    # New Zealand (incl. free association)
    "CK": "NZ", "NU": "NZ", "TK": "NZ",
    # Australia
    "CX": "AU", "CC": "AU", "NF": "AU", "HM": "AU",
    # Norway
    "SJ": "NO", "BV": "NO",
    # Finland
    "AX": "FI",
}

# Non-UN-member codes that deliberately do NOT fold into any state: they
# count on the "countries & territories" stat only. (Political neutrality:
# TW/XK/PS/VA are self-governing or disputed; AQ/EH belong to no state.)
STANDALONE_NON_MEMBERS = {"AQ", "EH", "PS", "TW", "VA", "XK"}


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate CountryCatalogData.swift from the mledoze countries dataset.")
    parser.add_argument("countries_json", type=Path, metavar="countries.json",
                        help="Local mledoze countries JSON dataset")
    args = parser.parse_args()
    rows = json.loads(args.countries_json.read_text())

    areas: dict[str, float] = {}
    un_members: set[str] = set()
    for row in rows:
        code = row["cca2"]
        area = row.get("area")
        if isinstance(area, (int, float)) and area > 0:
            areas[code] = float(area)
        if row.get("unMember"):
            un_members.add(code)

    # Dataset correction: mledoze marks the Holy See (VA) as a UN member;
    # it is a permanent OBSERVER (like Palestine), not one of the 193.
    un_members.discard("VA")

    if len(un_members) != 193:
        raise SystemExit(f"UN member count {len(un_members)} != 193 — dataset changed, re-audit")
    bad_keys = sorted(k for k in FOLDS if k in un_members)
    if bad_keys:
        raise SystemExit(f"fold keys are UN members themselves: {bad_keys}")
    bad_targets = sorted(v for v in FOLDS.values() if v not in un_members)
    if bad_targets:
        raise SystemExit(f"fold targets not UN members: {bad_targets}")
    unaccounted = sorted(
        c for c in (r["cca2"] for r in rows)
        if c not in un_members and c not in FOLDS and c not in STANDALONE_NON_MEMBERS
    )
    if unaccounted:
        raise SystemExit(f"non-member codes neither folded nor standalone: {unaccounted}")

    lines = [
        "// GENERATED by scripts/build-country-catalog.py — do not edit by hand.",
        "// Source: mledoze/countries, licensed under the ODbL 1.0",
        "// (https://opendatacommons.org/licenses/odbl/1-0/). Areas are total km²",
        "// (approximate; the UI always renders them behind a ≈). Regenerate with",
        "// the script.",
        "",
        "import Foundation",
        "",
        "nonisolated extension CountryCatalog {",
        "",
        "    /// Total area (km²) per ISO 3166-1 alpha-2 code.",
        "    static let areaKm2: [String: Double] = [",
    ]
    for code in sorted(areas):
        lines.append(f'        "{code}": {areas[code]:g},')
    lines += [
        "    ]",
        "",
        "    /// The 193 UN member states.",
        "    static let unMembers: Set<String> = [",
    ]
    members = sorted(un_members)
    for i in range(0, len(members), 12):
        chunk = ", ".join(f'"{c}"' for c in members[i : i + 12])
        lines.append(f"        {chunk},")
    lines += [
        "    ]",
        "",
        "    /// Dependent territory → sovereign UN member (for the UN-count fold).",
        "    /// Codes absent here and from `unMembers` (TW, XK, PS, VA, AQ, EH)",
        "    /// count only on the countries-&-territories stat.",
        "    static let sovereignOfTerritory: [String: String] = [",
    ]
    for code in sorted(FOLDS):
        lines.append(f'        "{code}": "{FOLDS[code]}",')
    lines += [
        "    ]",
        "",
        "    /// Every ISO 3166-1 alpha-2 code in the dataset — the canonical",
        "    /// \"is this a real country or territory\" membership test.",
        "    /// `Locale.Region.isoRegions` is CLDR data and ALSO carries",
        "    /// supranational codes (EU, EZ, UN…) that must never count as",
        "    /// countries anywhere in the app.",
        "    static let isoCountryCodes: Set<String> = [",
    ]
    all_codes = sorted(r["cca2"] for r in rows)
    for i in range(0, len(all_codes), 12):
        chunk = ", ".join(f'"{c}"' for c in all_codes[i : i + 12])
        lines.append(f"        {chunk},")
    lines += [
        "    ]",
        "",
        f"    /// Total ISO 3166-1 alpha-2 codes in the dataset ({len(rows)}).",
        f"    static let isoCodeTotal = {len(rows)}",
        "}",
        "",
    ]
    body = "\n".join(lines)
    tmp_path = OUT.with_name(OUT.name + ".tmp")
    try:
        tmp_path.write_text(body, encoding="utf-8")
        if tmp_path.read_text(encoding="utf-8") != body:
            raise RuntimeError("written country catalog does not match generated source")
        os.replace(tmp_path, OUT)
    finally:
        tmp_path.unlink(missing_ok=True)
    print(f"wrote {OUT} — {len(areas)} areas, {len(un_members)} UN members, {len(FOLDS)} folds")


if __name__ == "__main__":
    main()
