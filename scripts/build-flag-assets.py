#!/usr/bin/env python3
"""Generate TravelLog/Flags.xcassets and TravelLog/Views/Shared/FlagAssetCodes.swift
from the lipis/flag-icons 4:3 SVG set (https://github.com/lipis/flag-icons, MIT).

Emits one image set `flag-<iso>` per code in `CountryCatalog.isoCountryCodes`
(CountryCatalogData.swift): the upstream SVG converted to a 40x30 pt vector
PDF by librsvg (`rsvg-convert`), single scale, vector data preserved,
original rendering. The system SVG renderer mishandles upstream clip paths,
transforms and <use> references (Japan's disc off centre, the US and China
without stars, Venezuela blank), while PDFs draw through Core Graphics
exactly as librsvg resolved them. The 40x30 pt page keeps actool's
pre-rasterized bitmaps small; the flags never draw larger than 36 pt wide
and the preserved vector covers anything bigger.
Also emits the Swift set of shipped codes so `FlagView` never probes the
bundle per row.

Usage (pin the release; v7.5.0 is the one shipped; needs `brew install librsvg`):
  mkdir /tmp/flag-icons && cd /tmp/flag-icons
  curl -sL https://github.com/lipis/flag-icons/archive/refs/tags/v7.5.0.tar.gz | tar -xz
  python3 scripts/build-flag-assets.py /tmp/flag-icons/flag-icons-7.5.0/flags/4x3

The script hard-fails if any catalog code has no SVG or a conversion fails.
"""

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "TravelLog" / "Services" / "Geography" / "CountryCatalogData.swift"
ASSETS = ROOT / "TravelLog" / "Flags.xcassets"
SWIFT = ROOT / "TravelLog" / "Views" / "Shared" / "FlagAssetCodes.swift"
INFO = {"author": "xcode", "version": 1}
RSVG = shutil.which("rsvg-convert")


def catalog_codes():
    source = CATALOG.read_text()
    match = re.search(r"isoCountryCodes: Set<String> = \[(.*?)\]", source, re.S)
    if not match:
        raise SystemExit("isoCountryCodes not found in CountryCatalogData.swift")
    codes = sorted(set(re.findall(r'"([A-Z]{2})"', match.group(1))))
    if len(codes) < 240:
        raise SystemExit(f"suspiciously few catalog codes: {len(codes)}")
    return codes


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("svg_dir", type=Path, help="flag-icons flags/4x3 directory")
    args = parser.parse_args()

    if not RSVG:
        raise SystemExit("rsvg-convert not found (brew install librsvg)")
    codes = catalog_codes()
    missing = [c for c in codes if not (args.svg_dir / f"{c.lower()}.svg").is_file()]
    if missing:
        raise SystemExit(f"no 4:3 SVG for: {', '.join(missing)}")

    if ASSETS.exists():
        shutil.rmtree(ASSETS)
    ASSETS.mkdir()
    write_json(ASSETS / "Contents.json", {"info": INFO})
    for code in codes:
        iso = code.lower()
        imageset = ASSETS / f"flag-{iso}.imageset"
        imageset.mkdir()
        source = args.svg_dir / f"{iso}.svg"
        root = re.search(r"<svg\b[^>]*>", source.read_text())
        if not root or 'viewBox="0 0 640 480"' not in root.group(0) or re.search(r"\s(width|height)=", root.group(0)):
            raise SystemExit(f"{iso}.svg: unexpected root element")
        subprocess.run([RSVG, "-f", "pdf", "-w", "40", "-h", "30",
                        "-o", str(imageset / f"{iso}.pdf"), str(source)], check=True)
        write_json(imageset / "Contents.json", {
            "images": [{"filename": f"{iso}.pdf", "idiom": "universal"}],
            "info": INFO,
            "properties": {
                "preserves-vector-representation": True,
                "template-rendering-intent": "original",
            },
        })

    rows = []
    lowered = [c.lower() for c in codes]
    for start in range(0, len(lowered), 12):
        rows.append("        " + ", ".join(f'"{c}"' for c in lowered[start:start + 12]) + ",")
    SWIFT.write_text(
        "// GENERATED by scripts/build-flag-assets.py — do not edit by hand.\n"
        "// The `flag-<iso>` image sets shipped in Flags.xcassets (lipis/flag-icons,\n"
        "// MIT). Regenerate with the script.\n"
        "\n"
        "import Foundation\n"
        "\n"
        "nonisolated enum FlagAssetCodes {\n"
        "    /// Lowercase ISO 3166-1 alpha-2 codes that have a bundled flag.\n"
        "    static let shipped: Set<String> = [\n"
        + "\n".join(rows) + "\n"
        "    ]\n"
        "}\n"
    )
    print(f"wrote {len(codes)} flags to {ASSETS.relative_to(ROOT)} and {SWIFT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
